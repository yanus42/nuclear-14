using System.Globalization;
using System.Text.RegularExpressions;
using System.Text.Json;
using SixLabors.ImageSharp;
using SixLabors.ImageSharp.PixelFormats;

internal static class PortraitRegionGenerator
{
    public static void Main(string[] args)
    {
        var root = Path.GetFullPath(args[0]);
        var regions = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var pair = new Regex(@"sprite:\s*([^\r\n#]+?)\s*\r?\n\s*state:\s*([^\r\n#]+)");
        foreach (var yaml in Directory.EnumerateFiles(Path.Combine(root, "Resources/Prototypes"), "*.yml", SearchOption.AllDirectories))
        {
            var text = File.ReadAllText(yaml);
            if (!Regex.IsMatch(text, @"type:\s*marking\b")) continue;
            foreach (Match match in pair.Matches(text))
            {
                var path = match.Groups[1].Value.Trim().Trim('"', '\'').Replace('\\', '/').TrimStart('/');
                var state = match.Groups[2].Value.Trim().Trim('"', '\'');
                var key = path + "/" + state;
                if (regions.ContainsKey(key)) continue;
                var directory = Path.Combine(root, "Resources/Textures", path);
                var png = Path.Combine(directory, state + ".png");
                if (!File.Exists(png)) continue;
                using var meta = JsonDocument.Parse(File.ReadAllText(Path.Combine(directory, "meta.json")), new JsonDocumentOptions { AllowTrailingCommas = true, CommentHandling = JsonCommentHandling.Skip });
                var width = meta.RootElement.GetProperty("size").GetProperty("x").GetInt32();
                var height = meta.RootElement.GetProperty("size").GetProperty("y").GetInt32();
                using var image = Image.Load<Rgba32>(png);
                var left = float.PositiveInfinity; var top = float.PositiveInfinity;
                var right = float.NegativeInfinity; var bottom = float.NegativeInfinity;
                for (var y = 0; y < image.Height; y++)
                for (var x = 0; x < image.Width; x++)
                {
                    if (image[x, y].A < 16) continue;
                    var px = x % width - width / 2f + 16;
                    var py = y % height - height / 2f + 16;
                    left = Math.Min(left, px); top = Math.Min(top, py);
                    right = Math.Max(right, px + 1); bottom = Math.Max(bottom, py + 1);
                }
                if (!float.IsFinite(left)) continue;
                string F(float n) => n.ToString(CultureInfo.InvariantCulture) + "f";
                regions.Add(key, $"        [{JsonSerializer.Serialize(key)}] = new({F(left)}, {F(top)}, {F(right)}, {F(bottom)}),");
            }
        }
        var output = "// Generated by Tools/_Forge/AppearancePortraits/GeneratePortraitRegions.csproj; source alpha bounds across all poses.\nnamespace Content.Client._Forge.Humanoid;\n\npublic static partial class MarkingPortraitRegion\n{\n    private static readonly Dictionary<string, UIBox2> Bounds = new()\n    {\n" + string.Join("\n", regions.Values) + "\n    };\n}\n";
        File.WriteAllText(Path.Combine(root, "Content.Client/_Forge/Humanoid/MarkingPortraitRegion.Generated.cs"), output);
        Console.WriteLine($"Generated {regions.Count} sprite regions.");
    }
}
